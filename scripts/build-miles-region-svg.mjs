import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { geoNaturalEarth1, geoPath } from 'd3-geo'

const root = fileURLToPath(new URL('..', import.meta.url))
const sourceDirectory = `${root}/scripts/miles-goal`
const outputPath = `${root}/components/miles-goal/worldRegionPaths.ts`
const regionIds = [
  'uk_ireland', 'europe', 'america', 'north_africa', 'indian_subcontinent',
  'southeast_asia', 'philippines', 'russia_central_asia', 'china_east_asia',
  'australia_new_zealand', 'japan_korea', 'middle_east',
  'sub_saharan_africa', 'indian_ocean_islands',
]

const mapping = JSON.parse(await readFile(`${sourceDirectory}/country-region-map.json`, 'utf8'))
const world = JSON.parse(await readFile(`${sourceDirectory}/ne_110m_admin_0_map_units.geojson`, 'utf8'))
assert.deepEqual(Object.keys(mapping), regionIds, 'Country mapping must use the canonical Earnn region IDs')

const codeToRegion = new Map()
for (const [regionId, codes] of Object.entries(mapping)) {
  for (const code of codes) {
    assert.ok(!codeToRegion.has(code), `${code} is mapped twice`)
    codeToRegion.set(code, regionId)
  }
}

const width = 1100
const height = 560
const pathsByRegion = Object.fromEntries(regionIds.map((regionId) => [regionId, []]))

function regionForFeature(feature) {
  const code = feature.properties?.SU_A3 || feature.properties?.ADM0_A3 || feature.properties?.ISO_A3
  const parentCode = feature.properties?.ADM0_A3
  return codeToRegion.get(code) || codeToRegion.get(parentCode)
}

// Antarctica and the two explicitly documented non-country geometries are not
// selectable Earnn travel regions. Fit only the available product regions so
// the rendered map has no Antarctic strip or unnecessary world-map margins.
const selectableWorld = {
  type: 'FeatureCollection',
  features: world.features.filter((feature) => Boolean(regionForFeature(feature))),
}
const projection = geoNaturalEarth1().fitExtent([[0, 0], [width, height]], selectableWorld)
const toPath = geoPath(projection).digits(0)

for (const feature of selectableWorld.features) {
  const regionId = regionForFeature(feature)
  const path = toPath(feature)
  if (!path) continue
  pathsByRegion[regionId].push(path)
}

for (const regionId of regionIds) {
  assert.ok(pathsByRegion[regionId].length > 0, `${regionId} has no generated SVG geometry`)
}

const source = `// Generated by scripts/build-miles-region-svg.mjs. Do not edit manually.\n`
  + `import type { MilesRegionId } from '@/lib/miles-goal/regions'\n\n`
  + `export const WORLD_MAP_VIEWBOX = '0 0 ${width} ${height}'\n\n`
  + `export const REGION_SVG_PATHS = ${JSON.stringify(pathsByRegion)} as Record<MilesRegionId, readonly string[]>\n`

await writeFile(outputPath, source, 'utf8')
const outputBytes = Buffer.byteLength(source)
console.log(`Generated ${regionIds.length} interactive regions from ${world.features.length} Natural Earth map units (${outputBytes} bytes of SVG path data).`)
